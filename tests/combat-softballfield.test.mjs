import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { FIGHTERS, STAGES, ALL_STAGES, COSTUMES, getStage, getReplayFighter } from '../combat/data.mjs';
import { STORY_ROUTES } from '../combat/stories.mjs';
import { CombatEngine, FIXED_DT } from '../combat/engine.mjs';
import { createProgram, validateProgram, recordProgramResult, retryProgram, PROGRAM_MODES } from '../combat/progression.mjs';
import { emptyProfile, validateProfile, validateReplay, replayInputs, replayRulesVersion } from '../combat/session.mjs';
import { FIDELITY_SOURCES } from '../combat/fidelity.mjs';

const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const captured = readFileSync(new URL('./fixtures/combat-pre-softballfield.json', import.meta.url));
const baseline = JSON.parse(captured);
const clone = value => JSON.parse(JSON.stringify(value));

test('softballfield appends a distinct documented arena without changing historical stages or costumes', () => {
  assert.equal(hash(captured), '504bf44aaa1e84b46482385755ad468283ae84e95bb4c594f82b810bd0c65dfe', 'Keep the independent pre-addition fixture');
  assert.deepEqual(STAGES.slice(0, baseline.stageIds.length).map(stage => stage.id), baseline.stageIds);
  assert.equal(STAGES.filter(stage => stage.id === 'softballfield').length, 1);
  assert.equal(STAGES[baseline.stageIds.length].id, 'softballfield');
  assert.deepEqual(COSTUMES.slice(0, baseline.costumeCount).map(costume => costume.id), baseline.costumeIds);
  assert.equal(hash(JSON.stringify(COSTUMES.slice(0, baseline.costumeCount))), baseline.costumesSHA256);
  const stage = getStage('softballfield');
  assert.equal(stage.sourceId, 'ep5');
  assert.deepEqual([stage.width, stage.floor, stage.bounds.left, stage.bounds.right], [1280, 568, 65, 1215]);
  assert.deepEqual(stage.fidelity.sourceIds, ['ep5', 'glitch-softballfield-storyboards']);
  const source = FIDELITY_SOURCES.find(item => item.id === 'glitch-softballfield-storyboards');
  assert.equal(new URL(source.url).searchParams.get('t'), '1120');
  assert.match(source.url, /L4p2gN2CzsA/); assert.match(source.scope, /320 × 180/);
  for (const plane of ['far', 'mid', 'near']) {
    const native = readFileSync(new URL('../docs/art-generation/continuation-20261120-b/stage/native/' + plane + '.png', import.meta.url));
    const active = readFileSync(new URL('../assets/encore/stages/softballfield/' + plane + '.png', import.meta.url));
    assert.deepEqual(active, native, plane + ': native generated bytes changed');
    assert.deepEqual([...active.subarray(0, 8)], [137,80,78,71,13,10,26,10]);
    assert.deepEqual([active.readUInt32BE(16), active.readUInt32BE(20)], [plane === 'near' ? 1671 : 1672, 941], 'Keep the actual native dimensions; the near output is one pixel narrower');
  }
  assert.equal(hash(readFileSync(new URL('./fixtures/combat-pre-undermap.json', import.meta.url))), '3b50be4fe6c51b3cb47babf874eeb159db1b619d87f995aa9fcbde0ca19b9a0d');
  assert.equal(hash(readFileSync(new URL('./fixtures/combat-pre-barnoir.json', import.meta.url))), '96a3e7c26f1da9a391b3baefed824f7855ebfb76ec62c44282b5b722c29785f7');
});

test('all 54 story routes keep the content captured before the 25th arena', () => {
  assert.equal(Object.keys(baseline.storyRoutes).length, 54);
  for (const [id, expected] of Object.entries(baseline.storyRoutes)) {
    assert.equal(hash(JSON.stringify(STORY_ROUTES[id])), expected.sha256, id + ': full route changed');
    assert.deepEqual(STORY_ROUTES[id].chapters.map(chapter => ({ opponentId: chapter.opponentId, stageId: chapter.stageId })), expected.chapters);
  }
});

test('450 checkpoints from the 24-arena release retain draws, profiles, continuation and retries', () => {
  assert.equal(baseline.fixtures.length, 75);
  assert.ok(baseline.fixtures.some(item => item.start.initialStage === 'barnoir'));
  for (const fixture of baseline.fixtures) {
    for (const key of ['start', 'firstWin', 'secondWin', 'defeat', 'retry', 'completion']) {
      assert.deepEqual(validateProgram(clone(fixture[key])), fixture[key], fixture.player + '/' + fixture.mode + '/' + key);
      const profile = validateProfile({ ...emptyProfile(), program: clone(fixture[key]) });
      assert.deepEqual(profile.program, fixture[key].status === 'active' ? fixture[key] : null);
    }
    assert.deepEqual(recordProgramResult(clone(fixture.firstWin), { won: true, health: 6532 }), fixture.secondWin);
    assert.deepEqual(retryProgram(clone(fixture.defeat)), fixture.retry);
    let run = clone(fixture.start);
    while (run.status === 'active') run = recordProgramResult(clone(run), { won: true, health: 6532 });
    assert.deepEqual(run, fixture.completion, fixture.player + '/' + fixture.mode + '/completion');
  }
});

test('recognizing the 24-arena release does not accept a changed saved schedule', () => {
  for (const fixture of baseline.fixtures.filter(item => item.mode !== 'story')) {
    const corrupted = clone(fixture.firstWin);
    corrupted.stages[1] = 'softballfield';
    assert.throws(() => validateProgram(corrupted), /reprise/);
  }
});

test('new programmes can select and draw softballfield while stories keep their authored locations', () => {
  for (const mode of PROGRAM_MODES) {
    const run = createProgram(mode, 'pomni', FIGHTERS, STAGES, { seed: 20261120, stage: 'softballfield' });
    assert.deepEqual(validateProgram(clone(run)), run);
    if (mode === 'story') assert.deepEqual(run.stages, STORY_ROUTES.pomni.chapters.map(chapter => chapter.stageId));
    else assert.equal(run.stages[0], 'softballfield');
    assert.deepEqual(validateProgram(clone(recordProgramResult(run, { won: true, health: 6532 }))).stages, run.stages);
  }
  assert.ok(Array.from({ length: 32 }, (_, index) => createProgram('survival', 'pomni', FIGHTERS, STAGES, { seed: index + 1 }))
    .some(run => run.stages.includes('softballfield')));
});

test('four pre-softballfield replays including barnoir retain all 1052 frame fingerprints', () => {
  assert.equal(baseline.replays.length, 4);
  let frames = 0;
  for (const fixture of baseline.replays) {
    const replay = validateReplay(clone(fixture.replay), FIGHTERS.map(fighter => fighter.id), ALL_STAGES.map(stage => stage.id));
    const engine = new CombatEngine({ ...replay.config, fighters: replay.config.fighters.map(id => getReplayFighter(id, replay.version)),
      stage: getStage(replay.config.stage), rulesVersion: replayRulesVersion(replay.version) });
    const digest = createHash('sha256');
    for (const input of replayInputs(replay)) { engine.step(FIXED_DT, input); digest.update(JSON.stringify(engine.getSnapshot()) + '\n'); }
    assert.equal(digest.digest('hex'), fixture.allFrameSHA256, replay.config.stage);
    assert.equal(engine.getSnapshot().frame, fixture.frames); frames += fixture.frames;
  }
  assert.equal(frames, 1052);
});
