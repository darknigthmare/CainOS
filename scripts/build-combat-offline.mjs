import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { FIGHTERS, ARCHIVE, GAME } from '../combat/data.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const folder = path.join(root, 'combat');
const core = fs.readdirSync(folder).filter(name => /\.(?:mjs|js|css|html|svg|png|webmanifest)$/.test(name) && name !== 'offline-manifest.mjs').sort();
const illustrations = [];
const collectIllustrations = (directory) => {
  if (!fs.existsSync(directory)) return;
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) collectIllustrations(file);
    else if (entry.isFile() && /\.(?:webp|png)$/i.test(entry.name)) {
      illustrations.push(path.relative(folder, file).split(path.sep).join('/'));
    }
  }
};
collectIllustrations(path.join(root, 'assets/encore'));
const art = [...new Set([...ARCHIVE.map(item => item.sprite.src), ...FIGHTERS.map(f => f.sprite.src), ...FIGHTERS.filter(f => f.animation).map(f => f.animation.src), ...illustrations])].sort();
const hash = crypto.createHash('sha256');
const artHash = crypto.createHash('sha256');
let bytes = 0;
for (const name of [...core, ...art]) {
  const source = path.resolve(folder, name);
  if (!source.startsWith(root) || !fs.existsSync(source)) throw new Error('Missing offline file: ' + name);
  const data = fs.readFileSync(source);
  hash.update(name).update(data);
  if (art.includes(name)) { bytes += data.length; artHash.update(name).update(data); }
}
const version = GAME.version + '-' + hash.digest('hex').slice(0, 12);
const artVersion = artHash.digest('hex').slice(0, 16);
fs.writeFileSync(path.join(folder, 'offline-manifest.mjs'), '// Generated by scripts/build-combat-offline.mjs. Rebuild after changing combat or its assets.\nexport const OFFLINE_VERSION = ' + JSON.stringify(version) + ';\nexport const ART_VERSION = ' + JSON.stringify(artVersion) + ';\nexport const CORE_FILES = ' + JSON.stringify([...core, 'offline-manifest.mjs'].sort(), null, 2) + ';\nexport const ART_FILES = ' + JSON.stringify(art, null, 2) + ';\nexport const ART_BYTES = ' + bytes + ';\n');
console.log('Offline manifest: ' + version + ' / ' + art.length + ' illustrations / ' + bytes + ' bytes / art ' + artVersion + '.');
