"""Install reviewed static-base metadata; never modify native image bytes."""
from pathlib import Path
from PIL import Image
import hashlib, json

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / 'docs/art-generation/base-sprites-20261125'
def read(relative): return json.loads((FOLDER / relative).read_text())
def digest(value): return hashlib.sha256(value).hexdigest()

official = read('official/manifest.json')
originals = read('original-appearance-specs.json')
queenie = read('queenie-two-worlds/manifest.json')
sunset = read('root-sunset/manifest.json')
projectiles = read('projectiles-manifest.json')
native_records = [*official['assets'], *queenie['files'], *sunset['assets'], *projectiles['assets']]
native_by_file = {}
for record in native_records:
    file = record.get('file', record.get('path'))
    if not file and record.get('destination'):
        file = str(Path(record['destination']).relative_to(ROOT))
    assert file, record
    raw = (ROOT/file).read_bytes()
    assert digest(raw) == record['sha256'], file
    source = record.get('nativeOutput', record.get('source'))
    assert source and Path(source).read_bytes() == raw, file
    native_by_file[file] = record
assert len(native_by_file) == 32
assert len(official['families']) == 5 and len(originals) == 9
assert len(list((ROOT/'assets/encore/crossovers/murderdrones/queenie').rglob('*.png'))) == 6
assert len(list((ROOT/'assets/encore/crossovers/metarunner/queenie').rglob('*.png'))) == 6

definitions, reviews, inventory = [], {}, []
official_review_path = 'docs/art-generation/base-sprites-20261125/official/manifest.json'
for source in [*official['families'], *originals]:
    definition = {k:v for k,v in source.items() if k not in {'assetReview','references','visibleTraits','reviewPath','baseOnly','presentation','authoredSlots'}}
    definition['traits'] = source.get('visibleTraits', source.get('traits'))
    assert definition['traits']
    definition['introducedOn'] = '2026-11-25'
    definition['nativeFacing'] = source.get('nativeFacing', 1)
    assert definition['nativeFacing'] in [-1,1]
    definition['visual'] = source.get('visual', {'maxIllustratedWidth': 220})
    review_path = source.get('reviewPath', official_review_path)
    assert (ROOT/review_path).is_file()
    id_ = source['id']
    directory = source['directory'].removeprefix('../')
    hashes = {}
    for slot in ['selection','stance']:
        file = directory+'/'+slot+'.png'
        assert file in native_by_file
        raw = (ROOT/file).read_bytes()
        sha = digest(raw); hashes[slot] = sha
        with Image.open(ROOT/file) as im:
            assert im.mode == 'RGBA', file
            a = im.getchannel('A'); h = a.histogram()
            bounds = a.point(lambda v:255 if v > 12 else 0).getbbox()
            assert h[0] > 0 and bounds, file
            assert bounds[0] > 0 and bounds[1] > 0 and bounds[2] < im.width and bounds[3] < im.height, file
            inventory.append({'id':id_, 'slot':slot, 'file':file, 'sha256':sha, 'bytes':len(raw),
                'width':im.width,'height':im.height,'mode':im.mode,'alphaBounds':bounds,
                'alphaExtrema':a.getextrema(),'transparentFraction':h[0]/(im.width*im.height),
                'nativeBytesVerified':True,'reviewPath':review_path})
    assert hashes['selection'] != hashes['stance'], id_
    review = {
        'status':'verified-base-files','sha256':hashes,'captureId':review_path,
        'visibleTraits':definition['traits'],
        'identityEvidence':source.get('sourceTitle',source['name']),
        'framing':'Garde entière et portrait individuel ; silhouettes contenues dans le cadre au seuil alpha 12.',
        'transparency':'PNG RGBA natifs conservés sans retouche ; transparence réelle et marges vérifiées.',
        'proportions':'Proportions du dessin conservées par échelle uniforme ; orientation native déclarée.',
        'scope':source['scope'],'issues':[],
        'sourceUrls':source.get('sourceUrls',[source['sourceUrl']])
    }
    reviews[id_] = review; definitions.append(definition)
for row in projectiles['assets']:
    raw = (ROOT/row['file']).read_bytes()
    assert digest(raw) == row['sha256'] and len(raw) == row['bytes']
    inventory.append({**row,'nativeBytesVerified':True})
assert len(inventory)==32 and len({r['sha256'] for r in inventory})==32
assert len({d['id'] for d in definitions})==14
module = '// Reviewed individual static bases — 25 November 2026. Generated by the dated installer.\n'
module += 'export const CONTINUATION_BASE_DEFINITIONS = Object.freeze('+json.dumps(definitions,ensure_ascii=False,indent=2)+'.map(definition => Object.freeze(definition)));\n\n'
module += 'export const CONTINUATION_BASE_REVIEWS = Object.freeze('+json.dumps(reviews,ensure_ascii=False,indent=2)+');\n'
(ROOT/'combat/base-sprite-continuation-20261125.mjs').write_text(module)
(FOLDER/'asset-inventory.json').write_text(json.dumps({'schema':'encore-static-base-assets/v1',
    'createdOn':'2026-11-25','baselineCommit':'616a585274506f20c54386d8be07a76e75e1f198',
    'complete':True,'families':14,'characterImages':28,'projectileImages':4,'animations':0,
    'assets':inventory,'summary':{'files':32,'bytes':sum(r['bytes'] for r in inventory),'nativeRGBA':True,'distinctImages':32}
},ensure_ascii=False,indent=2)+'\n')
print(json.dumps({'families':len(definitions),'images':len(inventory),'bytes':sum(r['bytes'] for r in inventory)}))
